"use strict";
const assert = require("assert");
const fs = require("fs");
const path = require("path");
const { JSDOM } = require("jsdom");
const dom = new JSDOM("<!doctype html><body></body>", { runScripts: "outside-only" });
const w = dom.window;
w.eval(fs.readFileSync(path.join(__dirname, "../quam_state_manager/web/static/cz-plan.js"), "utf8"));
w.CzPlan._mountGateHint();
const host = w.document.getElementById("czg-host");
const settle = () => new Promise(resolve => w.setTimeout(resolve, 0));
const dialog = '<div class="ui-dialog-foot"><button id="czg-primary" disabled>Check</button></div>';
(async () => {
    host.innerHTML = dialog;
    await settle();
    let button = host.querySelector("button");
    let hint = host.querySelector("#czp-check-hint");
    assert(hint && !hint.hidden, "disabled Check explains its prerequisites");
    assert(hint.textContent.includes("valid gate plan and no invalid fields"));
    assert(hint.textContent.includes("active request"));
    assert(button.getAttribute("aria-describedby").split(/\s+/).includes(hint.id));
    button.disabled = false;
    await settle();
    assert(hint.hidden, "enabled Check needs no disabled hint");
    assert(!button.hasAttribute("aria-describedby"), "enabled Check drops the disabled description");
    button.disabled = true;
    button.textContent = "Create gate";
    await settle();
    assert(hint.hidden, "the Check hint does not label a disabled Create action");
    host.innerHTML = dialog;
    await settle();
    w.CzPlan._mountGateHint();
    assert.strictEqual(host.querySelectorAll("#czp-check-hint").length, 1, "reopening keeps one hint");
    assert(!host.querySelector("#czp-check-hint").hidden);
    host._czPlanHint.disconnect();
    w.close();
    console.log("all checks passed");
})().catch(error => { w.close(); console.error(error); process.exitCode = 1; });

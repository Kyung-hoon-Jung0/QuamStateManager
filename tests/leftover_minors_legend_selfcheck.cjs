'use strict';
const fs = require('fs');
const assert = require('assert');
const { dom, w, t, doc } = require('./leftover_minors_world.cjs')();
const style = doc.createElement('style');
style.textContent = fs.readFileSync(require('path').join(__dirname, '../quam_state_manager/web/static/ui-kit.css'), 'utf8');
doc.head.appendChild(style);
const app = fs.readFileSync(require('path').join(__dirname, '../quam_state_manager/web/static/app.js'), 'utf8');
const start = app.indexOf('function _appendWiringLegend(');
assert(start >= 0, 'legend function seam');
w.UI_CONFIG = { instrumentWiring: {} };
w._WIRING_ROLE_WORDS = {};
w.eval(app.slice(start, app.indexOf('\nvar _IW_THEMED_FILL', start)));
const host = doc.getElementById('gen-pop-wiring-diagram');
host.innerHTML = '<svg><g class="iw-port-circle" data-element="q1" data-role="xy"></g></svg>';
w._appendWiringLegend(host, {});
const item = host.querySelector('.iw-key-conflict');
assert(item, 'conflict key exists');
assert(item.hidden, 'hidden initially');
assert.equal(w.getComputedStyle(item).display, 'none');
t.markConflictPorts([{group: 'qubit', rid: 'q1'}], 'iw-port-conflict');
assert.equal(item.hidden, false, 'visible for a conflict');
assert.notEqual(w.getComputedStyle(item).display, 'none');
t.markConflictPorts([], 'iw-port-conflict');
assert.equal(item.hidden, true, 'hidden after clearing');
assert.equal(w.getComputedStyle(item).display, 'none');
dom.window.close();
console.log('all checks passed');

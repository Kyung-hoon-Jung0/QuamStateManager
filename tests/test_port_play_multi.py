@pytest.fixture
def spec():
    return {'network': {'host': 'scope-host', 'cluster_name': 'scope-cluster', 'port': 80},
            'instruments': {'controllers': [
                {'con': c, 'fems': [{'slot': 1, 'fem': 'mw'}, {'slot': 3, 'fem': 'lf'}]}
                for c in range(1, 3)]},
            'qubits': [], 'port_offsets': {'con1/3/2': {'offset': 0.05, 'output_mode': 'direct'}}}


def lf(port, offset=0.1, mode='direct'):
    return {'kind': 'lf', 'port': list(port), 'offset': offset, 'output_mode': mode}


def mw(port, band=2, lo=6e9, iff=50e6, fsp=1, amp=0.5):
    return {'kind': 'mw', 'port': list(port), 'band': band, 'lo_hz': lo, 'if_hz': iff, 'fsp': fsp, 'amp': amp}


def test_one_entry_is_the_one_port_builder_byte_for_byte(spec):
    for entry, single in [(lf(['con2', 3, 5], .12, 'amplified'), pt.build_wizard_dc(spec, ['con2', 3, 5], .12, 'amplified')),
                          (mw(['con1', 1, 4]), pt.build_wizard_mw(spec, ['con1', 1, 4], 2, 6e9, 50e6, 1, 0.5))]:
        cfg, plan = pt.build_wizard_multi(spec, [entry])
        assert (cfg, plan) == single
        assert 'plays' not in plan
        a, b = pt.render_script(cfg, plan), pt.render_script(*single)
        strip = lambda t: '\n'.join(l for l in t.splitlines() if not l.startswith('Generated by'))
        assert strip(a) == strip(b)
        assert 'PLAYS' not in a


def test_two_lf_ports(spec):
    baseline = copy.deepcopy(spec)
    cfg, plan = pt.build_wizard_multi(spec, [lf(['con1', 3, 1], .1), lf(['con2', 3, 7], -.3, 'amplified')])
    assert spec == baseline
    outs = lambda c: cfg['controllers'][c]['fems']['3']['analog_outputs']
    assert outs('con1')['1']['offset'] == .1
    assert outs('con2')['7'] == dict(outs('con2')['7'], offset=-.3, output_mode='amplified')
    assert outs('con1')['2']['offset'] == 0.05  # a saved offset elsewhere is kept
    assert cfg['elements']['sm_port_play']['singleInput']['port'] == ('con1', 3, 1)
    assert cfg['elements']['sm_port_play_2']['singleInput']['port'] == ('con2', 3, 7)
    assert cfg['elements']['sm_port_play_2']['operations'] == {'dc': 'sm_port_play_2.pulse'}
    assert cfg['pulses']['sm_port_play_2.pulse']['waveforms'] == {'single': 'sm_port_play_2.zero'}
    assert set(cfg['waveforms']) == {'sm_port_play.zero', 'sm_port_play_2.zero'}
    assert plan['test'] == 'dc' and [p['element'] for p in plan['plays']] == ['sm_port_play', 'sm_port_play_2']
    assert plan['config_fingerprint'] == pt.config_fingerprint(cfg)


def test_three_mixed_ports_and_script(spec):
    cfg, plan = pt.build_wizard_multi(spec, [mw(['con1', 1, 4]), lf(['con2', 3, 5], .2),
                                             mw(['con1', 1, 6], band=3, lo=8e9, amp=0.25)])
    mwout = cfg['controllers']['con1']['fems']['1']['analog_outputs']
    assert set(mwout) == {'4', '6'}  # only the played MW ports are declared
    assert mwout['6']['band'] == 3 and mwout['6']['upconverter_frequency'] == 8e9
    assert cfg['controllers']['con2']['fems']['1'] == {'type': 'MW'}
    assert cfg['controllers']['con2']['fems']['3']['analog_outputs']['5']['offset'] == .2
    assert cfg['elements']['sm_port_play_3']['MWInput']['port'] == ('con1', 1, 6)
    assert cfg['waveforms']['sm_port_play_3.amp']['sample'] == 0.25
    assert cfg['elements']['sm_port_play_2']['singleInput']['port'] == ('con2', 3, 5)
    assert plan['test'] == 'cw' and any('port delays compensate' in n for n in plan['notes'])
    # D-10/D-11: band 2 (port 4) is the slowest MW band; the band-3 port waits the difference.
    assert cfg['controllers']['con2']['fems']['3']['analog_outputs']['5']['delay'] == 161
    assert mwout['4']['delay'] == 0 and mwout['6']['delay'] == 20
    script = pt.render_script(cfg, plan)
    assert "PLAYS = [('sm_port_play', 'cw'), ('sm_port_play_2', 'dc'), ('sm_port_play_3', 'cw')]" in script
    assert 'for _el, _op in PLAYS:\n                    play(_op * amp(AMP_SCALE), _el)' in script
    assert 'play(OPERATION * amp(AMP_SCALE), ELEMENT)' not in script
    assert 'Plays together: con1/1/4, con2/3/5, con1/1/6' in script
    compile(script, '<multi>', 'exec')


def test_all_lf_and_all_mw_have_no_delay(spec):
    for entries in ([lf(['con1', 3, 1]), dict(lf(['con1', 3, 2]), delay_ns=99)],
                    [mw(['con1', 1, 4], band=1, lo=5e9), mw(['con1', 1, 6], band=2, lo=6e9)]):
        cfg, plan = pt.build_wizard_multi(spec, entries)
        assert 'delay' not in json.dumps(cfg) and not any('delay' in n for n in plan['notes'])
        assert all('delay_ns' not in p for p in plan['plays'])


def test_single_port_ignores_delay(spec):
    single = pt.build_wizard_dc(spec, ['con1', 3, 1], 0.1, 'direct')
    assert pt.build_wizard_multi(spec, [dict(lf(['con1', 3, 1]), delay_ns=50)]) == single


def test_mixed_bands_align_to_slowest(spec):
    # D-11: band 2 is the slowest MW band; the band-1 MW port waits the 20 ns difference.
    cfg, plan = pt.build_wizard_multi(spec, [lf(['con1', 3, 1]), mw(['con1', 1, 4], band=1, lo=5e9),
                                             mw(['con1', 1, 6], band=2, lo=6e9)])
    mwout = cfg['controllers']['con1']['fems']['1']['analog_outputs']
    assert cfg['controllers']['con1']['fems']['3']['analog_outputs']['1']['delay'] == 161
    assert mwout['4']['delay'] == 20 and mwout['6']['delay'] == 0
    assert [p['delay_ns'] for p in plan['plays']] == [161, 20, 0]


def test_lf_delay_is_editable_and_validated(spec):
    cfg, _ = pt.build_wizard_multi(spec, [dict(lf(['con1', 3, 1]), delay_ns=150), mw(['con1', 1, 4])])
    assert cfg['controllers']['con1']['fems']['3']['analog_outputs']['1']['delay'] == 150
    for bad in (-1, 16001, 1.5, True, '10'):
        with pytest.raises(pt.PortTestError, match='LF delay'):
            pt.build_wizard_multi(spec, [dict(lf(['con1', 3, 1]), delay_ns=bad), mw(['con1', 1, 4])])



def _app(tmp_path, monkeypatch):
    from quam_state_manager.web import port_test_routes as routes
    from quam_state_manager.core import config_generator
    app = create_app(testing=True, instance_path=str(tmp_path / 'instance'))
    manager = routes.ptr.Runs(tmp_path / 'runs', resume=False)
    app.config['port_test_runs'] = manager
    monkeypatch.setattr(config_generator, 'known_interpreter', lambda p, _: p == sys.executable)
    return app, manager


def _confirmed(client, body):
    r = client.post('/port-play/confirm', json=dict(body, hardware_ok=True))
    assert r.status_code == 200, r.json
    return dict(body, confirm_token=r.json['token'])


def test_route_runs_every_port_and_binds_each_value(spec, tmp_path, monkeypatch):
    app, manager = _app(tmp_path, monkeypatch)
    captured = {}
    monkeypatch.setattr(manager, 'start', lambda python, script, request, meta: captured.update(
        script=script, meta=meta) or {'id': 'mock'})
    extra = [{'kind': 'lf', 'con': 'con2', 'slot': 3, 'port': 6, 'offset': .2, 'output_mode': 'direct', 'delay_ns': 170},
             {'kind': 'mw', 'con': 'con1', 'slot': 1, 'port': 4, 'band': 2, 'lo_hz': 6e9, 'if_hz': 5e7,
              'full_scale_power_dbm': 1, 'amp': .3}]
    body = dict(spec=spec, python=sys.executable, con='con2', slot=3, port=5, offset=.1, max_s=12, extra=extra,
                delay_ns=150)
    client = app.test_client()
    other = copy.deepcopy(extra); other[1]['amp'] = .4
    stale = _confirmed(client, dict(body, extra=other))
    assert client.post('/port-play/run', json=dict(stale, extra=extra)).status_code == 400
    no_extra = _confirmed(client, dict(body, extra=[]))
    assert client.post('/port-play/run', json=dict(no_extra, extra=extra)).status_code == 400
    r = client.post('/port-play/run', json=_confirmed(client, body))
    assert r.status_code == 200, r.json
    plays = captured['meta']['plan']['plays']
    assert [p['port'] for p in plays] == [['con2', 3, 5], ['con2', 3, 6], ['con1', 1, 4]]
    assert [p['delay_ns'] for p in plays] == [150, 170, 0]  # each LF delay reached the builder
    moved = _confirmed(client, dict(body, delay_ns=151))
    assert client.post('/port-play/run', json=dict(moved, delay_ns=150)).status_code == 400
    assert 'PLAYS = ' in captured['script']
    too_many = dict(body, extra=extra + [dict(extra[0], port=7)])
    assert client.post('/port-play/confirm', json=dict(too_many, hardware_ok=True)).status_code == 400
    dup = dict(body, extra=[dict(extra[0], port=5)])
    r = client.post('/port-play/confirm', json=dict(dup, hardware_ok=True))
    assert r.status_code == 400 and 'twice' in r.json['error']



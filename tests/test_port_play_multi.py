def test_jsdom():
    env = dict(os.environ, NODE_PATH=os.environ.get('NODE_PATH', str(ROOT / 'node_modules')))
    r = subprocess.run(['node', str(ROOT / 'tests' / 'port_play_multi_selfcheck.cjs')], cwd=ROOT,
                       capture_output=True, text=True, encoding='utf-8', env=env, timeout=120)
    if 'Cannot find module' in r.stderr and 'jsdom' in r.stderr:
        pytest.skip('jsdom not installed')
    assert r.returncode == 0, r.stdout + r.stderr
    assert 'port play multi selfcheck ok' in r.stdout

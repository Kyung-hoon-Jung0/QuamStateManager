"""The CZ gate plan's two-flux SNZ waveform matches the lab's own pulse class sample for sample
(goldens generated by the class itself, on synthetic parameters). It is a CZ-only transcription:
the pulse catalog does not carry the class, so the Pulses page keeps drawing it with the lab's code."""
import json
from pathlib import Path

import numpy as np
import pytest

from quam_state_manager.core import pulse_catalog, waveform_synth

CASES = json.loads((Path(__file__).parent / "golden" / "two_flux_waveforms.json").read_text())["cases"]


@pytest.mark.parametrize("case", CASES, ids=lambda c: f"A{c['params']['amplitude']}-u{c['params'].get('unipolar', False)}")
def test_samples_and_length_match_the_lab_class(case):
    params = {k: v for k, v in case["params"].items() if k != "length"}
    assert waveform_synth._snz_two_flux_length(params) == case["inferred_length"]
    pulse = {"__class__": "lab.pkg.SNZTwoFluxPulse", "length": "#./inferred_length", **params}
    samples = waveform_synth.lab_waveform(pulse)          # length inferred like the class does
    np.testing.assert_allclose(samples, case["samples"], rtol=0, atol=1e-12)


def test_a_unipolar_line_has_zero_net_area_and_a_bipolar_one_both_lobes():
    for case in CASES:
        s = np.asarray(case["samples"])
        if case["params"].get("unipolar"):
            assert abs(s.sum()) < 1e-9 and (s > 0).any() and (s < 0).any()
        else:
            assert (s > 0).any() and (s < 0).any()


def test_the_catalog_does_not_carry_the_lab_class():
    assert "SNZTwoFluxPulse" not in pulse_catalog.PULSE_CATALOG
    assert waveform_synth.lab_waveform({"__class__": "x.SquarePulse", "amplitude": .1, "length": 8}) is None

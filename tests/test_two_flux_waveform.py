"""The two-flux SNZ pulse preview matches the lab's own pulse class sample for sample
(goldens generated by the class itself, on synthetic parameters)."""
import json
from pathlib import Path

import numpy as np
import pytest

from quam_state_manager.core import pulse_catalog, waveform_synth

CASES = json.loads((Path(__file__).parent / "golden" / "two_flux_waveforms.json").read_text())["cases"]


@pytest.mark.parametrize("case", CASES, ids=lambda c: f"A{c['params']['amplitude']}-u{c['params'].get('unipolar', False)}")
def test_samples_and_length_match_the_lab_class(case):
    params = dict(case["params"])
    assert pulse_catalog.inferred_length("SNZTwoFluxPulse", {k: v for k, v in params.items() if k != "length"}) \
        == case["inferred_length"]
    out = waveform_synth.synthesize("SNZTwoFluxPulse", params)
    assert out["ok"], out
    np.testing.assert_allclose(out["i"], case["samples"], rtol=0, atol=1e-12)


def test_a_unipolar_line_has_zero_net_area_and_a_bipolar_one_both_lobes():
    for case in CASES:
        s = np.asarray(case["samples"])
        if case["params"].get("unipolar"):
            assert abs(s.sum()) < 1e-9 and (s > 0).any() and (s < 0).any()
        else:
            assert (s > 0).any() and (s < 0).any()
